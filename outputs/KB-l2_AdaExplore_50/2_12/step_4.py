def gemm_mul_lrelu(x, w_t, bias, multiplier, negative_slope):
    M, K = x.shape
    K2, N = w_t.shape
    assert K == K2
    x = x.contiguous()
    out = torch.empty((M, N), device=x.device, dtype=x.dtype)

    grid = lambda META: (triton.cdiv(M, META['BLOCK_M']) * triton.cdiv(N, META['BLOCK_N']),)

    gemm_mul_lrelu_kernel[grid](
        x, w_t, bias, out,
        M, N, K,
        x.stride(0), x.stride(1),
        w_t.stride(0), w_t.stride(1),
        out.stride(0), out.stride(1),
        MULTIPLIER=float(multiplier),
        NEG_SLOPE=float(negative_slope),
    )
    return out


class ModelNew(nn.Module):
    def __init__(self, in_features, out_features, multiplier, negative_slope):
        super().__init__()
        self.gemm = nn.Linear(in_features, out_features)
        self.multiplier = float(multiplier)
        self.negative_slope = float(negative_slope)
        self._w_t_cache = None

    def _get_w_t(self):
        w = self.gemm.weight
        if (self._w_t_cache is None
                or self._w_t_cache.device != w.device
                or self._w_t_cache.dtype != w.dtype
                or self._w_t_cache.data_ptr() == 0
                or self._w_t_cache.shape != (w.shape[1], w.shape[0])):
            self._w_t_cache = w.t().contiguous()
        return self._w_t_cache

    def forward(self, x):
        x = x.cuda()
        if self.gemm.weight.device != x.device:
            self.gemm.to(x.device)
            self._w_t_cache = None
        w_t = self._get_w_t()
        bias = self.gemm.bias.contiguous()
        return gemm_mul_lrelu(x, w_t, bias, self.multiplier, self.negative_slope)